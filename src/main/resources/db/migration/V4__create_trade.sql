-- 第 6 題：交易表。2.0 起持股改由「每次買賣」重播計算，1.0 的舊持股在這裡轉成一筆推估的買進
-- 注意：這個檔案一旦 commit 就不能再改；之後資料表有任何變動，一律新增 V5__、V6__…

CREATE TABLE trade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- 屬於哪一檔持股；holding 一個代號一筆，/api/v1 的 id 繼續用 holding.id
    holding_id      BIGINT         NOT NULL,
    -- 存 BUY 或 SELL（對應 Java enum 名稱）；欄位不叫 type，避免和日後除權息的「種類」混淆
    side            VARCHAR(4)     NOT NULL,
    -- 不叫 date：DATE 是 SQL 保留字
    trade_date      DATE           NOT NULL,
    -- 股數用 BIGINT：零股、超過 999 張、配股後都放得下（1.0 的 INT 張數上限是 999）
    shares          BIGINT         NOT NULL,
    -- 和 holding.buy_price 一樣用 DECIMAL(12, 2)，對應 Java 的 BigDecimal
    price           DECIMAL(12, 2) NOT NULL,
    -- 日期是推估的（1.0 轉入、App 1.0 新增）時為 TRUE；使用者改過日期後改成 FALSE
    date_estimated  BOOLEAN        NOT NULL,
    -- 樂觀鎖的版本號：修改、刪除時比對，不一致代表別的裝置已經改過
    version         BIGINT         NOT NULL,
    -- 由程式用台北時區的 Clock 寫入，不依賴主機時區
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    -- 約束都自己取名字：日後要調整時，新的 migration 才能用名字 DROP CONSTRAINT
    CONSTRAINT pk_trade         PRIMARY KEY (id),
    -- 刪除持股時一併刪除它的交易：現有的刪除功能（只刪 holding）才不會因為外鍵而失敗
    CONSTRAINT fk_trade_holding FOREIGN KEY (holding_id) REFERENCES holding (id) ON DELETE CASCADE,
    CONSTRAINT ck_trade_side    CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT ck_trade_shares  CHECK (shares > 0),
    CONSTRAINT ck_trade_price   CHECK (price > 0),
    -- 題目範圍從 2021 年開始；「不能是未來日期」要看今天，CHECK 做不到，由程式用 Clock 判斷
    CONSTRAINT ck_trade_date    CHECK (trade_date >= DATE '2021-01-01')
);

-- 最常用的查詢：某檔持股的全部交易，依日期、id 排序（重播順序）。
-- holding_id 放第一欄，外鍵檢查和「刪持股時找出它的交易」也用得到這個索引
CREATE INDEX idx_trade_holding_date ON trade (holding_id, trade_date, id);

-- 1.0 的每筆持股轉成一筆買進：張數 × 1000 = 股數，買進價 = 成交價。
-- 1.0 沒有記買進日期，用建立時間的日期推估（created_at 本來就是台北時間，CAST 不會跨日），並標記為推估。
-- GREATEST：建立日期早於 2021-01-01 時（正常使用不會發生，只有手動改過資料庫才會）拉到 2021-01-01。
-- 轉入的日期本來就是推估，拉到最早日期一樣標示推估；但保證不管什麼資料庫，V4 都不會被 ck_trade_date 擋下而無法啟動
-- 時間欄位沿用持股原本的值，不用 CURRENT_TIMESTAMP：那是主機時區，不是台北時間
INSERT INTO trade (holding_id, side, trade_date, shares, price, date_estimated, version, created_at, updated_at)
SELECT id, 'BUY', GREATEST(CAST(created_at AS DATE), DATE '2021-01-01'), CAST(lots AS BIGINT) * 1000, buy_price,
       TRUE, 0, created_at, updated_at
FROM holding;

-- 放寬 V1 的限制：2.0 的股數、成本改由交易計算，零股、0 張、超過 999 張都要能存。
-- 舊欄位這一版先保留（擴充 → 遷移 → 收縮），之後再用新的 migration 刪除
ALTER TABLE holding DROP CONSTRAINT ck_holding_lots;
ALTER TABLE holding DROP CONSTRAINT ck_holding_buy_price;
ALTER TABLE holding ALTER COLUMN lots DROP NOT NULL;
ALTER TABLE holding ALTER COLUMN buy_price DROP NOT NULL;
