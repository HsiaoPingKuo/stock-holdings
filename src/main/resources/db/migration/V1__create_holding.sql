-- 第 2 題：持股資料表
-- 注意：這個檔案一旦 commit 就不能再改；之後資料表有任何變動，一律新增 V2__、V3__…

CREATE TABLE holding (
    -- 用流水號當主鍵（App 1.0 用 id 修改、刪除）；不拿代號當主鍵，日後同代號允許多筆也不用改主鍵
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 代號一定用字串，0050 開頭的 0 才不會掉；10 字涵蓋 00631L 這類代號
    code        VARCHAR(10)    NOT NULL,
    lots        INT            NOT NULL,
    -- 金額用 DECIMAL，對應 Java 的 BigDecimal，避免浮點誤差
    buy_price   DECIMAL(12, 2) NOT NULL,
    -- 由程式用台北時區的 Clock 寫入，不依賴主機時區
    created_at  TIMESTAMP      NOT NULL,
    updated_at  TIMESTAMP      NOT NULL,
    -- 約束都自己取名字：日後要調整時，新的 migration 才能用名字 DROP CONSTRAINT
    CONSTRAINT uk_holding_code      UNIQUE (code),
    CONSTRAINT ck_holding_lots      CHECK (lots BETWEEN 1 AND 999),
    CONSTRAINT ck_holding_buy_price CHECK (buy_price > 0)
);
