-- 第 6 題：除權息資料。背景同步把官方的除權息列表（上市 TWT49U、上櫃 exDailyQ）存進來，
-- 重播交易時只讀這兩張表，使用者的請求不呼叫官方 API（CLAUDE.md 2.1）。
-- 注意：這個檔案一旦 commit 就不能再改；之後資料表有任何變動，一律新增 V6__、V7__…

CREATE TABLE dividend_event (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- 存 TWSE 或 TPEX（對應 Java enum 名稱）
    market                     VARCHAR(4)     NOT NULL,
    code                       VARCHAR(10)    NOT NULL,
    -- 官方名稱尾端有空白，存之前先去掉；只用來寫 log 和除錯，畫面上的名稱仍以持股為準
    name                       VARCHAR(50),
    -- 除權息交易日；不叫 date：DATE 是 SQL 保留字
    ex_date                    DATE           NOT NULL,
    -- 存 CASH、STOCK、CASH_AND_STOCK（對應 DividendKind），官方的「息／權／權息」「除息／除權／除權息」
    kind                       VARCHAR(14)    NOT NULL,

    -- ===== 列表的原始值：存下來才能在拿到明細、或規則修正後重新判斷，不必再打官方 =====
    -- 所有數字都用 DECIMAL(18, 8)：上櫃的配股率有 8 位小數（例如 99.99999623），整數部分還留 10 位給股價
    prev_close                 DECIMAL(18, 8),
    ex_right_reference         DECIMAL(18, 8),
    -- 權值＋息值 = 前收 − 除權息參考價，是股價差額，不一定等於配發的股利（設計決定 7-C）
    rights_plus_dividend       DECIMAL(18, 8),
    dividend_reference         DECIMAL(18, 8),
    -- 只有上櫃列表有：每股現金股利、每仟股無償配股；上市是 NULL
    listed_cash_per_share      DECIMAL(18, 8),
    listed_stock_per_thousand  DECIMAL(18, 8),
    -- 只有上市有：明細 API 的參數（列表的「詳細資料」欄位，例如 2884,20250722）
    detail_stock_no            VARCHAR(10),
    detail_date                DATE,

    -- ===== 上市明細的結果 =====
    -- NOT_NEEDED（上櫃，或用列表就算得出官方值）／PENDING（待查）／FOUND（查到）／
    -- NOT_FOUND（官方說沒有這筆，不再查）／FAILED（連線或格式失敗，隔天再試）
    detail_status              VARCHAR(10)    NOT NULL,
    detail_cash_per_share      DECIMAL(18, 8),
    detail_stock_per_thousand  DECIMAL(18, 8),
    -- 最後一次查明細的時間（台北時間，由程式用 Clock 寫入）；FAILED 用它判斷「今天查過了沒」
    detail_checked_at          TIMESTAMP,

    -- ===== 依 DividendSourceRule 算出來、重播時採用的值 =====
    -- 無法取得時兩個都是 NULL（不猜數字，也不計入股利和配股）
    cash_per_share             DECIMAL(18, 8),
    stock_per_thousand         DECIMAL(18, 8),
    -- OFFICIAL（官方）／ESTIMATED（估算）／UNAVAILABLE（無法取得）
    source                     VARCHAR(11)    NOT NULL,

    -- 最後一次在列表裡看到這筆的時間；時間欄位都由程式用台北時區的 Clock 寫入，不用 CURRENT_TIMESTAMP（主機時區）
    list_fetched_at            TIMESTAMP      NOT NULL,
    created_at                 TIMESTAMP      NOT NULL,
    updated_at                 TIMESTAMP      NOT NULL,

    -- 約束都自己取名字：日後要調整時，新的 migration 才能用名字 DROP CONSTRAINT
    CONSTRAINT pk_dividend_event                  PRIMARY KEY (id),
    -- 同一個市場、同一檔、同一天只有一次除權息；重抓今年時靠它找到同一筆來更新，不會多一列
    CONSTRAINT uk_dividend_event_market_code_date UNIQUE (market, code, ex_date),
    CONSTRAINT ck_dividend_event_market           CHECK (market IN ('TWSE', 'TPEX')),
    CONSTRAINT ck_dividend_event_kind             CHECK (kind IN ('CASH', 'STOCK', 'CASH_AND_STOCK')),
    CONSTRAINT ck_dividend_event_detail_status    CHECK (detail_status IN ('NOT_NEEDED', 'PENDING', 'FOUND', 'NOT_FOUND', 'FAILED')),
    CONSTRAINT ck_dividend_event_source           CHECK (source IN ('OFFICIAL', 'ESTIMATED', 'UNAVAILABLE')),
    -- 和 DividendEventInput 的檢查一致：無法取得 → 兩個都 NULL；其他 → 兩個都有、而且不是負數。
    -- 要明寫 IS NOT NULL：CHECK 遇到 NULL 的比較結果是「未知」，會被當成通過
    CONSTRAINT ck_dividend_event_amounts CHECK (
        (source = 'UNAVAILABLE' AND cash_per_share IS NULL AND stock_per_thousand IS NULL)
        OR (source <> 'UNAVAILABLE'
            AND cash_per_share IS NOT NULL AND cash_per_share >= 0
            AND stock_per_thousand IS NOT NULL AND stock_per_thousand >= 0)),
    -- 查到明細時，明細的兩個數字一定要存下來，之後才能重新判斷
    CONSTRAINT ck_dividend_event_detail_found CHECK (
        detail_status <> 'FOUND'
        OR (detail_cash_per_share IS NOT NULL AND detail_stock_per_thousand IS NOT NULL)),
    -- 題目範圍從 2021 年開始
    CONSTRAINT ck_dividend_event_ex_date CHECK (ex_date >= DATE '2021-01-01')
);

-- 重播時最常用的查詢：某幾檔的全部事件，依除權息日排序。
-- 唯一約束的索引第一欄是 market，用代號查用不到，所以另外建
CREATE INDEX idx_dividend_event_code_date ON dividend_event (code, ex_date);

-- 哪個市場、哪一年的列表抓過了。有這一列 = 抓過（就算那一年真的沒有除權息也會有一列），
-- 才分得出「真的沒有除權息」和「還沒抓」
CREATE TABLE dividend_fetch_range (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    market           VARCHAR(4)  NOT NULL,
    -- 不叫 year：YEAR 在 H2 是關鍵字
    fetch_year       INT         NOT NULL,
    -- 在那一年結束之後才抓的 → TRUE，之後不再抓；今年（或年底前抓的）一律 FALSE，下一輪會重抓
    completed        BOOLEAN     NOT NULL,
    -- 最後一次成功抓到列表（有資料或確定沒資料）的時間，台北時間
    last_fetched_at  TIMESTAMP   NOT NULL,
    CONSTRAINT pk_dividend_fetch_range             PRIMARY KEY (id),
    CONSTRAINT uk_dividend_fetch_range_market_year UNIQUE (market, fetch_year),
    CONSTRAINT ck_dividend_fetch_range_market      CHECK (market IN ('TWSE', 'TPEX')),
    CONSTRAINT ck_dividend_fetch_range_year        CHECK (fetch_year >= 2021)
);
