-- 第 6 題：冪等鍵（Idempotency Key）。/api/v2 的寫入和 2.0 網頁表單帶一個鍵，
-- 網路不穩重送、連按兩下時，同一個鍵只處理一次，第二次直接回傳上次的結果（設計決定 6-A）。
-- 注意：這個檔案一旦 commit 就不能再改；之後資料表有任何變動，一律新增 V7__、V8__…

CREATE TABLE idempotency_record (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- 用戶端產生的 UUID（36 字），留一點空間；格式由 controller 檢查
    idempotency_key  VARCHAR(64)  NOT NULL,
    -- 方法＋路徑樣板，例如 'POST /api/v2/trades'、'PUT /api/v2/trades/{id}'；同一個鍵換一支 API 用也算重複使用
    api              VARCHAR(100) NOT NULL,
    -- 請求內容的 SHA-256（64 個十六進位字元）：同一個鍵、內容不同時才分得出來，不必存整個請求
    request_hash     CHAR(64)     NOT NULL,
    -- IN_PROGRESS（寫入中）／COMPLETED（完成）。鍵和交易在同一個資料庫交易裡寫入，
    -- 別的連線只會看到 COMPLETED；「處理中」是靠下面的 UNIQUE 擋下或等不到鎖判斷的
    status           VARCHAR(11)  NOT NULL,
    -- 上次回給用戶端的狀態碼和內容，重送時原樣回傳；完成前是 NULL
    response_status  INT,
    -- 回應的 JSON 長度不固定，用 CLOB 不必猜上限
    response_body    CLOB,
    -- 由程式用台北時區的 Clock 寫入；清除過期紀錄時用它判斷
    created_at       TIMESTAMP    NOT NULL,
    -- 約束都自己取名字：日後要調整時，新的 migration 才能用名字 DROP CONSTRAINT
    CONSTRAINT pk_idempotency_record      PRIMARY KEY (id),
    -- 整個機制靠這個 UNIQUE：同一個鍵同時送兩次，第二個 INSERT 會被擋下或等待第一個結束
    CONSTRAINT uk_idempotency_record_key  UNIQUE (idempotency_key),
    CONSTRAINT ck_idempotency_record_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED')),
    -- 完成的紀錄一定要有狀態碼，重送時才回得出上次的結果
    CONSTRAINT ck_idempotency_record_done CHECK (status <> 'COMPLETED' OR response_status IS NOT NULL)
);

-- 每小時刪除超過 24 小時的紀錄時用（WHERE created_at < ?）
CREATE INDEX idx_idempotency_record_created_at ON idempotency_record (created_at);
