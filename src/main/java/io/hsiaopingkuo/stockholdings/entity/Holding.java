package io.hsiaopingkuo.stockholdings.entity;

import java.time.LocalDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * 一筆持股，對應 V1__create_holding.sql 的 holding 表（V2 加上 name、market）。
 * 資料表由 Flyway 建立，這裡的 @Column 只是對應欄位，Hibernate 啟動時會檢查兩邊一致（ddl-auto=validate）。
 *
 * 第 6 題：股數、成本改由 trade 表的交易重播計算，這裡不再對應 lots、buy_price。
 * 兩個欄位先留在資料庫（V4 已拿掉 NOT NULL），新增的持股寫入 NULL；之後再用新的 migration 刪除。
 */
@Entity
@Table(name = "holding")
public class Holding {

	@Id
	// IDENTITY：由資料庫自動編號，對應 SQL 的 GENERATED BY DEFAULT AS IDENTITY
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Long id;

	@Column(name = "code", nullable = false, length = 10)
	private String code;

	// 第 3 題（V2 migration）加入；第 2 題時存的舊資料沒有名稱和市場，所以允許 null
	@Column(name = "name", length = 50)
	private String name;

	// 存 enum 名稱（TWSE／TPEX）而不是序號：資料庫裡看得懂，日後調整 enum 順序也不會對錯
	@Enumerated(EnumType.STRING)
	@Column(name = "market", length = 4)
	private Market market;

	@Column(name = "created_at", nullable = false)
	private LocalDateTime createdAt;

	@Column(name = "updated_at", nullable = false)
	private LocalDateTime updatedAt;

	// JPA 規定要有無參數建構子（讀資料庫時用）；設成 protected，避免其他程式建出欄位是空的持股
	protected Holding() {
	}

	// 時間由呼叫端傳入（service 用台北時區的 Clock 算好），Entity 自己不碰系統時間
	// 名稱和市場在新增時由官方 API 判斷後一起存入，之後不能改；股數和價格記在交易（Trade）
	public Holding(String code, String name, Market market, LocalDateTime now) {
		this.code = code;
		this.name = name;
		this.market = market;
		this.createdAt = now;
		this.updatedAt = now;
	}

	public Long getId() {
		return id;
	}

	public String getCode() {
		return code;
	}

	public String getName() {
		return name;
	}

	public Market getMarket() {
		return market;
	}

	public LocalDateTime getCreatedAt() {
		return createdAt;
	}

	public LocalDateTime getUpdatedAt() {
		return updatedAt;
	}
}
